import fs from "fs";
import path from "path";

const PAYMENT_HEADERS = {
  "Content-Type": "application/json",
  "anthropic-version": "2023-06-01",
};

export async function generateFromClaude(prompt: string, target: string, filename: string) {
  const apiKey = process.env.CLAUDE_API_KEY;

  if (!apiKey) {
    return {
      content: `--METADATA--{"filename":"${filename}","path":"${target}"}--METADATA--\n\n` + `local target = "${target}"\nprint("Demo generated by Roblox Claude App")\n`,
      mode: "demo",
    };
  }

  try {
    const response = await fetch("https://api.anthropic.com/v1/messages", {
      method: "POST",
      headers: {
        ...PAYMENT_HEADERS,
        "x-api-key": apiKey,
      },
      body: JSON.stringify({
        model: "claude-3-5-sonnet-20240620",
        max_tokens: 1600,
        messages: [
          {
            role: "user",
            content: prompt,
          },
        ],
        system:
          "You are a Roblox code generator. Output only Lua code or GUI creation logic. If metadata is needed, include a single JSON metadata line formatted exactly as --METADATA--{...}--METADATA-- at the top. Follow security restrictions: no external network, no os.execute, no IO, no suspicious code.",
      }),
    });

    if (!response.ok) {
      throw new Error(`Claude API error: ${response.status}`);
    }

    const data = await response.json();
    const text = data?.content?.[0]?.text || "";
    if (!text) throw new Error("No content returned");

    return {
      content: text,
      mode: "claude",
    };
  } catch (error) {
    console.error("Claude API generation failed:", error);
    return {
      content: `--METADATA--{"filename":"${filename}","path":"${target}"}--METADATA--\n\nprint("Fallback generation from app. Please configure CLAUDE_API_KEY.")\n`,
      mode: "fallback",
    };
  }
}

export function readPromptTemplate() {
  const filePath = path.join(process.cwd(), "templates", "promptTemplate.txt");
  return fs.readFileSync(filePath, "utf8");
}
